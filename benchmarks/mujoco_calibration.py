"""Deterministic MuJoCo actuator identification and calibration preflight.

The identification run uses synthetic traces generated by the local MuJoCo
plant.  Primary traces are used for fitting; held-out traces are evaluated only
after fitting and are never passed to the optimizer.  This is a reproducible
check of the simulator path, not a physical actuator calibration or a safety
validation result.

The free-space identification probes set ``gravity_z=0`` so force and torque
transmission can be separated from floor contact.  A separate friction sweep
keeps the default gravity and reports contact-dependent diagnostics without
fitting a safety margin or making a safety claim.
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import json
import sys
from dataclasses import asdict, dataclass, replace
from pathlib import Path
from typing import TYPE_CHECKING, Any, Iterable, Sequence, cast

import numpy as np

if TYPE_CHECKING:
    from benchmarks.mujoco_scene import MuJoCoPlantConfig


PARAMETER_NAMES = (
    "tau_v",
    "tau_omega",
    "force_gain",
    "torque_gain",
    "slip_gain",
)
REQUIRED_MEASURED_LOG_FIELDS = {
    "command_v": {"applied_command_v", "command_v", "requested_command_v"},
    "command_omega": {
        "applied_command_omega",
        "command_omega",
        "requested_command_omega",
    },
    "measured_v": {"v", "measured_v", "velocity_v"},
    "measured_omega": {"omega", "measured_omega", "yaw_rate"},
    "dt": {"dt", "sample_dt", "timestep"},
    "friction": {"friction", "floor_friction"},
}


@dataclass(frozen=True)
class CalibrationProbe:
    """Immutable deterministic command sequence for one identification probe."""

    name: str
    split: str
    dt: float
    friction: float
    initial_state: tuple[float, float, float, float, float]
    commands: tuple[tuple[float, float], ...]
    gravity_z: float = 0.0

    def __post_init__(self) -> None:
        if self.split not in {"primary", "held-out", "friction-diagnostic"}:
            raise ValueError(f"unsupported calibration split: {self.split}")
        if self.dt <= 0.0 or not np.isfinite(self.dt):
            raise ValueError("probe dt must be positive and finite")
        if self.friction < 0.0 or not np.isfinite(self.friction):
            raise ValueError("probe friction must be nonnegative and finite")
        if not np.isfinite(self.gravity_z):
            raise ValueError("probe gravity_z must be finite")
        initial_state = np.asarray(self.initial_state, dtype=float)
        if initial_state.shape != (5,) or not np.all(np.isfinite(initial_state)):
            raise ValueError("initial_state must be a finite 5-vector")
        if not self.commands:
            raise ValueError("probe commands must not be empty")
        command_array = np.asarray(self.commands, dtype=float)
        if command_array.shape != (len(self.commands), 2) or not np.all(
            np.isfinite(command_array)
        ):
            raise ValueError("probe commands must be finite pairs")

    @property
    def command_array(self) -> np.ndarray:
        """Return a fresh ``(steps, 2)`` command array."""

        return np.asarray(self.commands, dtype=float).copy()


@dataclass
class CalibrationTrace:
    """One MuJoCo replay trace and simulator-only diagnostic states."""

    probe: CalibrationProbe
    states: np.ndarray
    actuator_states: np.ndarray
    contact_counts: np.ndarray


def _validated_trace(trace: CalibrationTrace) -> CalibrationTrace:
    """Validate and copy complete traces before fitting or evaluating them.

    Checking exact shapes prevents NumPy broadcasting from treating a single
    row as an entire observation sequence. Revalidate at use time because the
    arrays in a trace are mutable after construction.
    """

    if not isinstance(trace, CalibrationTrace) or not isinstance(trace.probe, CalibrationProbe):
        raise ValueError("expected a CalibrationTrace with a CalibrationProbe")
    trace.probe.__post_init__()
    steps = len(trace.probe.commands)
    arrays: dict[str, np.ndarray] = {}
    for name, shape in (
        ("states", (steps, 5)),
        ("actuator_states", (steps, 2)),
        ("contact_counts", (steps,)),
    ):
        try:
            values = np.asarray(getattr(trace, name), dtype=float)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"trace {trace.probe.name!r} {name} must be numeric") from exc
        if values.shape != shape or not np.all(np.isfinite(values)):
            raise ValueError(
                f"trace {trace.probe.name!r} {name} must be finite with shape {shape}"
            )
        arrays[name] = values.copy()
    counts = arrays["contact_counts"]
    if np.any(counts < 0) or np.any(counts != np.floor(counts)):
        raise ValueError("contact_counts must contain nonnegative integer counts")
    return CalibrationTrace(probe=trace.probe, **arrays)


def _state_residual(predicted: np.ndarray, observed: np.ndarray) -> np.ndarray:
    """Use the same principal yaw difference for fitting and every error metric."""

    error = predicted - observed
    if not np.all(np.isfinite(error)):
        raise ValueError("state residual must be finite")
    error[:, 2] = np.arctan2(np.sin(error[:, 2]), np.cos(error[:, 2]))
    return error


@dataclass(frozen=True)
class FitEstimate:
    """Identified parameters from primary traces only."""

    tau_v: float
    tau_omega: float
    force_gain: float
    torque_gain: float
    slip_gain: float
    cost: float
    nfev: int
    success: bool
    message: str

    def as_parameter_dict(self) -> dict[str, float]:
        return {name: float(getattr(self, name)) for name in PARAMETER_NAMES}


@dataclass(frozen=True)
class SplitMetrics:
    """Prediction error for one explicit split."""

    split: str
    probe_count: int
    sample_count: int
    position_rmse_m: float
    heading_rmse_rad: float
    linear_velocity_rmse_mps: float
    angular_velocity_rmse_rps: float
    maximum_state_abs_error: float
    actuator_lag_rmse: float
    contact_samples: int


def _repeat_commands(
    blocks: Sequence[tuple[int, float, float]],
) -> tuple[tuple[float, float], ...]:
    commands: list[tuple[float, float]] = []
    for count, v_cmd, omega_cmd in blocks:
        if count <= 0:
            raise ValueError("command block lengths must be positive")
        commands.extend([(float(v_cmd), float(omega_cmd))] * count)
    return tuple(commands)


