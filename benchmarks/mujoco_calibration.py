def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run deterministic MuJoCo actuator identification diagnostics"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("Output/Plots/Paper/mujoco_calibration"),
    )
    parser.add_argument(
        "--measured-log",
        type=Path,
        default=None,
        help="Optional measured CSV path to check during preflight.",
    )
    parser.add_argument(
        "--preflight-only",
        action="store_true",
        help="Write runtime and measured-data checks without fitting synthetic traces.",
    )
    parser.add_argument("--max-nfev", type=int, default=60)
    return parser


def main(argv: Sequence[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    preflight = calibration_preflight(args.measured_log)
    if args.preflight_only:
        report: dict[str, Any] = {
            "metadata": {
                "evidence_kind": "calibration_preflight",
                "safety_claim_supported": False,
            },
            "preflight": preflight,
        }
    else:
        report = run_synthetic_calibration(max_nfev=args.max_nfev)
        report["preflight"] = preflight
    write_report(args.output, report)
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
